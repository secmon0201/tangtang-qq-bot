    @staticmethod
    def _parse_dynamic_rich_nodes(value: object) -> list[dict[str, str]]:
        if not isinstance(value, str) or not value:
            return []
        try:
            raw_nodes = json.loads(value)
        except (TypeError, ValueError):
            return []
        if not isinstance(raw_nodes, list):
            return []
        nodes: list[dict[str, str]] = []
        for raw_node in raw_nodes:
            if not isinstance(raw_node, dict):
                continue
            node_type = str(raw_node.get("type") or "text")
            text = str(raw_node.get("text") or "")
            url = str(raw_node.get("url") or "")
            if node_type == "emoji" and url:
                nodes.append({"type": "emoji", "text": text, "url": url})
            elif node_type == "link" and text:
                nodes.append({"type": "link", "text": text, "url": url})
            elif text:
                nodes.append({"type": "text", "text": text})
        return nodes

    @staticmethod
    def _parse_dynamic_image_urls(value: object) -> list[str]:
        if not isinstance(value, str) or not value:
            return []
        try:
            raw_urls = json.loads(value)
        except (TypeError, ValueError):
            return []
        if not isinstance(raw_urls, list):
            return []
        return [str(url) for url in raw_urls if str(url).startswith(("https://", "http://"))]

    def _load_dynamic_images(self, urls: list[str]) -> list[Image.Image | None]:
        return [self._remote_image(url) for url in urls]

    @staticmethod
    def _scaled_image_height(source: Image.Image | None, width: int, fallback: int) -> int:
        if source is None or source.width <= 0 or source.height <= 0:
            return fallback
        return max(1, round(width * source.height / source.width))

    def _dynamic_image_grid_layout(
        self, images: list[Image.Image | None], available_width: int
    ) -> list[tuple[Image.Image | None, int, int, int, int]]:
        if not images:
            return []
        gap = 12
        columns = 1 if len(images) == 1 else min(3, len(images))
        tile_width = (available_width - gap * (columns - 1)) // columns
        layout: list[tuple[Image.Image | None, int, int, int, int]] = []
        cursor_y = 0
        for row_start in range(0, len(images), columns):
            row = images[row_start:row_start + columns]
            heights = [self._scaled_image_height(source, tile_width, tile_width) for source in row]
            row_height = max(heights)
            for column, (source, height) in enumerate(zip(row, heights, strict=True)):
                left = column * (tile_width + gap)
                layout.append((source, left, cursor_y, tile_width, height))
            cursor_y += row_height + gap
        return layout

    @staticmethod
    def _dynamic_image_grid_height(layout: list[tuple[Image.Image | None, int, int, int, int]]) -> int:
        if not layout:
            return 0
        return max(top + height for _, _, top, _, height in layout)

    def _draw_dynamic_image_grid(
        self,
        image: Image.Image,
        layout: list[tuple[Image.Image | None, int, int, int, int]],
        left: int,
        top: int,
    ) -> None:
        if not layout:
            return
        draw = ImageDraw.Draw(image)
        for source, offset_x, offset_y, width, height in layout:
            box = (left + offset_x, top + offset_y, left + offset_x + width, top + offset_y + height)
            draw.rounded_rectangle(box, radius=16, fill="#f6eff4")
            self._paste_full_image(image, source, box)

    def _layout_dynamic_nodes(
        self,
        nodes: list[dict[str, str]],
        font: ImageFont.ImageFont,
        max_width: int,
        emoji_size: int = 42,
    ) -> list[list[tuple[str, str]]]:
        lines: list[list[tuple[str, str]]] = [[]]
        current_width = 0
        for node in nodes:
            if node.get("type") == "emoji":
                if current_width and current_width + emoji_size > max_width:
                    lines.append([])
                    current_width = 0
                lines[-1].append(("emoji", str(node["url"])))
                current_width += emoji_size + 4
                continue
            for character in str(node.get("text") or ""):
                if character == "\n":
                    lines.append([])
                    current_width = 0
                    continue
                token_width = self._text_width(character, font)
                if current_width and current_width + token_width > max_width:
                    lines.append([])
                    current_width = 0
                lines[-1].append(("link" if node.get("type") == "link" else "text", character))
                current_width += token_width
        return lines if any(lines) else [[("text", "（无文字内容）")]]

    def _layout_dynamic_body(
        self,
        text: str,
        emoji_assets: list[tuple[str, str]],
        font: ImageFont.ImageFont,
        max_width: int,
    ) -> list[list[tuple[str, str]]]:
        lines: list[list[tuple[str, str]]] = [[]]
        current_width = 0
        remaining = list(emoji_assets)
        index = 0
        while index < len(text):
            if text[index] == "\n":
                lines.append([])
                current_width = 0
                index += 1
                continue
            matched = next(
                ((position, label, url) for position, (label, url) in enumerate(remaining) if text.startswith(label, index)),
                None,
            )
            if matched is not None:
                position, label, url = matched
                token_width = 42
                if current_width and current_width + token_width > max_width:
                    lines.append([])
                    current_width = 0
                lines[-1].append(("emoji", url))
                current_width += token_width + 4
                remaining.pop(position)
                index += len(label)
                continue
            character = text[index]
            token_width = self._text_width(character, font)
            if current_width and current_width + token_width > max_width:
                lines.append([])
                current_width = 0
            lines[-1].append(("text", character))
            current_width += token_width
            index += 1
        return [line for line in lines if line] or [[("text", "（无文字内容）")]]

