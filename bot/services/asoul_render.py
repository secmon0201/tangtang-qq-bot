    def _remote_image(self, url: str) -> Image.Image | None:
        if not url.startswith(("https://", "http://")):
            return None
        cached = self._remote_cache.get(url)
        if cached is not None:
            return cached.copy()

        candidates = self._remote_image_candidates(url)
        headers = {
            "User-Agent": "Mozilla/5.0",
            "Referer": "https://www.bilibili.com/",
            "Accept": "image/avif,image/webp,image/apng,image/*,*/*;q=0.8",
        }
        for candidate in candidates:
            for attempt in range(3):
                try:
                    request = Request(candidate, headers=headers)
                    with urlopen(request, timeout=10) as response:
                        with Image.open(BytesIO(response.read())) as source:
                            result = source.convert("RGBA")
                    self._remote_cache[url] = result
                    return result.copy()
                except Exception:
                    if attempt < 2:
                        sleep(0.25 * (attempt + 1))
        return None

    @staticmethod
    def _remote_image_candidates(url: str) -> list[str]:
        """Prefer HTTPS and rotate Bilibili image hosts during CDN failures."""
        parsed = urlsplit(url)
        if not parsed.hostname:
            return [url]

        scheme = "https" if parsed.scheme in {"http", "https"} else parsed.scheme
        hosts = [parsed.netloc]
        hostname = parsed.hostname.lower()
        if hostname in {"i0.hdslb.com", "i1.hdslb.com", "i2.hdslb.com"}:
            port = f":{parsed.port}" if parsed.port else ""
            hosts.extend(f"{host}{port}" for host in ("i0.hdslb.com", "i1.hdslb.com", "i2.hdslb.com"))

        candidates: list[str] = []
        for host in hosts:
            candidate = urlunsplit((scheme, host, parsed.path, parsed.query, ""))
            if candidate not in candidates:
                candidates.append(candidate)
        return candidates


    @staticmethod
    def _paste_full_image(
        image: Image.Image, source: Image.Image | None, box: tuple[int, int, int, int]
    ) -> bool:
        if source is None:
            return False
        left, top, right, bottom = box
        width, height = right - left, bottom - top
        resized = source.resize((width, height), Image.Resampling.LANCZOS)
        image.alpha_composite(resized, (left, top))
        return True

    def _paste_circle(self, image: Image.Image, url: str, left: int, top: int, size: int, fallback: str) -> None:
        ImageDraw.Draw(image).ellipse((left, top, left + size, top + size), fill=fallback)
        source = self._remote_image(url)
        if source is None:
            return
        scale = max(size / source.width, size / source.height)
        resized = source.resize((round(source.width * scale), round(source.height * scale)), Image.Resampling.LANCZOS)
        x = (resized.width - size) // 2
        y = (resized.height - size) // 2
        avatar = resized.crop((x, y, x + size, y + size))
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, size, size), fill=255)
        image.paste(avatar, (left, top), mask)

    def _paste_emoji(self, image: Image.Image, url: str, left: int, top: int, size: int) -> None:
        source = self._remote_image(url)
        if source is None:
            ImageDraw.Draw(image).rounded_rectangle((left, top, left + size, top + size), radius=12, fill="#eceaf2")
            return
        scale = min(size / source.width, size / source.height)
        resized = source.resize((max(1, round(source.width * scale)), max(1, round(source.height * scale))), Image.Resampling.LANCZOS)
        x = left + (size - resized.width) // 2
        y = top + (size - resized.height) // 2
        image.alpha_composite(resized, (x, y))

    @staticmethod
    def _qr_image(url: str, size: int) -> Image.Image | None:
        try:
            qr = qrcode.QRCode(version=None, box_size=8, border=2)
            qr.add_data(url)
            qr.make(fit=True)
            return qr.make_image(fill_color="#252733", back_color="#ffffff").convert("RGBA").resize((size, size), Image.Resampling.NEAREST)
        except Exception:
            return None

    @staticmethod
    def _format_stat(value: str | None) -> str:
        try:
            number = int(str(value or "0"))
        except ValueError:
            return "--"
        if number >= 10_000:
            return f"{number / 10_000:.1f}".rstrip("0").rstrip(".") + "万"
        return str(number)

    def select_schedule_sticker(self, hosts: Iterable[str]) -> Path | None:
        """Choose one local sticker belonging to the scheduled hosts."""
        stickers = self._sticker_map()
        candidates = [path for host in hosts for path in stickers.get(str(host), [])]
        return random.choice(candidates) if candidates else None

    def _sticker_map(self) -> dict[str, list[Path]]:
        if self._stickers is not None:
            return self._stickers
        result: dict[str, list[Path]] = {}
        if self.sticker_dir.is_dir():
            for directory in self.sticker_dir.iterdir():
                if directory.is_dir():
                    result[directory.name] = [path for path in directory.glob("*.png") if path.is_file()]
        self._stickers = result
        return result

