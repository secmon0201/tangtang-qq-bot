class ASoulImageRenderer:
    """Pillow cards styled after the original A-SOUL plugin's schedule output."""

    WIDTH = 1080
    EDGE = 28
    LEFT = 56
    RIGHT = 56
    _WEEKDAYS = ("周一", "周二", "周三", "周四", "周五", "周六", "周日")
    _HIGHLIGHTS = {
        "粉色": ("#fff1f6", "#d9658b", "#f7d7e4"),
        "红色": ("#fff2ef", "#b84e45", "#efd0ca"),
        "白金色": ("#fffdf5", "#9c8050", "#eee2c8"),
    }

    def __init__(
        self,
        output_dir: Path,
        font_path: Path | None = None,
        sticker_dir: Path | None = None,
    ) -> None:
        self.output_dir = output_dir / "asoul"
        self.font_path = font_path
        self.sticker_dir = sticker_dir or RESOURCE_DIR / "asoul_stickers"
        self._fonts: dict[tuple[int, bool], ImageFont.ImageFont] = {}
        self._stickers: dict[str, list[Path]] | None = None
        self._remote_cache: dict[str, Image.Image] = {}

    async def render_schedule(self, target_day: date, title: str, items: Iterable[Any]) -> Path:
        return await asyncio.to_thread(
            self._render_schedule,
            target_day,
            title,
            list(items),
        )

    async def render_week_schedule(self, day_items: Iterable[tuple[date, Iterable[Any]]]) -> Path:
        prepared = [(target_day, list(items)) for target_day, items in day_items]
        return await asyncio.to_thread(self._render_week_schedule, prepared)

    async def render_bilibili_notification(
        self,
        text: str,
        live: dict[str, str] | None = None,
        dynamic: dict[str, str] | None = None,
        video: dict[str, str] | None = None,
    ) -> Path:
        return await asyncio.to_thread(self._render_bilibili_notification, text, live, dynamic, video)

    def _render_schedule(self, target_day: date, title: str, items: list[Any]) -> Path:
        return self._render_calendar(
            [(target_day, items)],
            f"{target_day:%Y-%m-%d} {title}",
            f"{title}排班",
        )

    def _render_week_schedule(self, day_items: list[tuple[date, list[Any]]]) -> Path:
        first = day_items[0][0] if day_items else date.today()
        return self._render_calendar(day_items, f"{first:%Y-%m-%d} 起 本周直播", "本周排班")

    def _render_calendar(
        self,
        day_items: list[tuple[date, list[Any]]],
        heading: str,
        subtitle: str,
    ) -> Path:
        layouts = [(target_day, self._day_layout(items)) for target_day, items in day_items]
        body_height = sum(layout["height"] for _, layout in layouts) + max(0, len(layouts) - 1) * 24
        header_height = 218
        footer_height = 48
        height = max(450, self.EDGE * 2 + header_height + body_height + footer_height + 24)
        image = Image.new("RGBA", (self.WIDTH, height), "#fff8fb")
        draw = EmojiTextDraw(image)
        self._draw_background(draw, height)
        draw.rounded_rectangle(
            (self.EDGE, self.EDGE, self.WIDTH - self.EDGE, height - self.EDGE),
            radius=32,
            fill="#fffefd",
            outline="#f5dce7",
            width=2,
        )
        self._draw_header(image, draw, heading, subtitle, sum(len(items) for _, items in day_items))
        y = self.EDGE + header_height + 24
        for target_day, layout in layouts:
            self._draw_day(draw, image, y, target_day, layout)
            y += layout["height"] + 24
        draw.text(
            (self.WIDTH - self.RIGHT - self._text_width("爱驼推送 / Generated by LEN", self._font(16)), height - 49),
            "爱驼推送 / Generated by LEN",
            font=self._font(16),
            fill="#a98a98",
        )
        draw_heart_tail(draw, 82, height - 43)
        return self._save(image, "schedule")

    def _draw_background(self, draw: ImageDraw.ImageDraw, height: int) -> None:
        draw.rectangle((0, 0, self.WIDTH, height), fill="#fff8fb")
        draw.rectangle((0, 0, 12, height), fill="#fff0f6")

    def _draw_header(self, image: Image.Image, draw: ImageDraw.ImageDraw, heading: str, subtitle: str, count: int) -> None:
        top = self.EDGE
        bottom = top + 218
        paste_horizontal_gradient(
            image,
            (self.EDGE, top, self.WIDTH - self.EDGE, bottom),
            "#f3a2bd",
            "#fff4f8",
            radius=32,
        )
        draw.rounded_rectangle((self.LEFT + 12, top + 40, self.LEFT + 160, top + 80), radius=18, fill="#ffffff")
        draw.text((self.LEFT + 31, top + 49), "A-SOUL LIVE", font=self._font(18), fill="#ee5e91")
        draw.text(
            (self.LEFT + 12, top + 97),
            self._ellipsize(heading, self._font(50, True), 800),
            font=self._font(50, True),
            fill="#352932",
        )
        draw.text((self.LEFT + 12, top + 166), subtitle, font=self._font(23), fill="#987c89")
        count_text = f"{count} 条安排"
        draw.text(
            (self.WIDTH - self.RIGHT - self._text_width(count_text, self._font(27)), top + 166),
            count_text,
            font=self._font(27),
            fill="#ee5e91",
        )
        draw_stitched_mascot(draw, self.WIDTH - self.RIGHT - 88, top + 10, 50)

    def _day_layout(self, items: list[Any]) -> dict[str, Any]:
        rows: list[dict[str, Any]] = []
        for item in items:
            sticker = self.select_schedule_sticker(getattr(item, "hosts", ()) or ())
            content_width = 514 if sticker else 704
            lines = self._wrap(str(getattr(item, "content", "")), self._font(29), content_width, 2)
            row_height = max(138, 76 + len(lines) * 39)
            rows.append({"item": item, "sticker": sticker, "lines": lines, "height": row_height})
        if not rows:
            return {"rows": [], "height": 170}
        return {"rows": rows, "height": 76 + sum(row["height"] for row in rows) + 18 * (len(rows) - 1) + 24}

    def _draw_day(
        self,
        draw: ImageDraw.ImageDraw,
        image: Image.Image,
        y: int,
        target_day: date,
        layout: dict[str, Any],
    ) -> None:
        height = int(layout["height"])
        draw.rounded_rectangle(
            (self.LEFT, y, self.WIDTH - self.RIGHT, y + height),
            radius=26,
            fill="#fffefd",
            outline="#f3dce6",
            width=2,
        )
        heading = f"{target_day.month}月{target_day.day}日  {self._WEEKDAYS[target_day.weekday()]}"
        draw.text((self.LEFT + 28, y + 24), heading, font=self._font(34, True), fill="#352932")
        count_text = f"{len(layout['rows'])} 条"
        draw.text(
            (self.WIDTH - self.RIGHT - 30 - self._text_width(count_text, self._font(21)), y + 34),
            count_text,
            font=self._font(21),
            fill="#ee5e91",
        )
        if not layout["rows"]:
            draw.text((self.LEFT + 30, y + 102), "还没有查到直播安排", font=self._font(28), fill="#a58996")
            return
        row_y = y + 76
        for row in layout["rows"]:
            self._draw_schedule_row(draw, image, row_y, row)
            row_y += int(row["height"]) + 18

    def _draw_schedule_row(self, draw: ImageDraw.ImageDraw, image: Image.Image, y: int, row: dict[str, Any]) -> None:
        item = row["item"]
        row_height = int(row["height"])
        highlighted = bool(getattr(item, "highlighted", False))
        fill, color, time_fill = self._HIGHLIGHTS.get(
            str(getattr(item, "highlight_style", "")),
            ("#fffafd", "#553843", "#ffe5ef"),
        )
        draw.rounded_rectangle(
            (self.LEFT + 22, y, self.WIDTH - self.RIGHT - 22, y + row_height),
            radius=22,
            fill=fill,
            outline="#f0dbe4" if not highlighted else color,
            width=2 if highlighted else 1,
        )
        draw.rounded_rectangle((self.LEFT + 46, y + 20, self.LEFT + 194, y + row_height - 20), radius=18, fill=time_fill)
        time_text = f"{item.starts_at:%H:%M}"
        self._draw_centered(draw, self.LEFT + 120, y + row_height // 2, time_text, self._font(31, True), color)
        content_x = self.LEFT + 230
        label = str(getattr(item, "label", "直播"))
        draw.rounded_rectangle(
            (content_x, y + 22, content_x + self._text_width(label, self._font(17, True)) + 28, y + 52),
            radius=15,
            fill=color,
        )
        draw.text((content_x + 14, y + 28), label, font=self._font(17, True), fill="#ffffff")
        hosts = " / ".join(getattr(item, "hosts", ()) or ()) or "待确认"
        draw.text((content_x, y + 61), self._ellipsize(hosts, self._font(21), 500), font=self._font(21), fill="#967987")
        lines = row["lines"] or ["直播内容待定"]
        line_y = y + 91
        for line in lines:
            draw.text((content_x, line_y), line, font=self._font(29), fill="#352932")
            line_y += 37
        if row["sticker"]:
            self._paste_sticker(image, row["sticker"], self.WIDTH - self.RIGHT - 204, y + 12, 160, row_height - 24)

