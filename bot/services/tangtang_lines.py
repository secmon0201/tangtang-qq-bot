_last_pick: dict[str, str] = {}


def _pick(category: str, texts: tuple[str, ...]) -> str:
    previous = _last_pick.get(category)
    choices = [text for text in texts if text != previous] or list(texts)
    chosen = random.choice(choices)
    _last_pick[category] = chosen
    return chosen


def profile_already_running() -> str:
    """Random Tangtang-style reply for a duplicate profile request."""
    return _pick("profile_already_running", PROFILE_ALREADY_RUNNING_TEXTS)


def profile_started() -> str:
    """Random Tangtang-style reply when a profile task starts."""
    return _pick("profile_started", PROFILE_STARTED_TEXTS)
